"""Write docs/API.md, the HTTP API reference, from the app's own OpenAPI schema.

    uv run python scripts/generate_api_reference.py

Offline and in-process: it builds the app with `normapi.app.create_app()` and
reads `app.openapi()`; no server, no database (NORM_PG_DSN is ignored). Swagger
UI and ReDoc stay off (ADR-023), so this file is the human-readable reference.
The output is sorted and carries no timestamp, so
tests/unit/test_api_reference.py can fail when it is stale.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import normapi.app

_ROOT = Path(__file__).resolve().parents[1]
OUT = _ROOT / "docs/API.md"
_METHODS = ("get", "post", "put", "patch", "delete")


def _cell(text: object) -> str:
    """One Markdown table cell: a single line, pipes escaped."""
    return " ".join(str(text).split()).replace("|", "\\|")


def _type(schema: dict[str, Any]) -> str:
    """A short type label; a component schema becomes a link to its section."""
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return f"[{name}](#{name.lower()})"
    for key in ("anyOf", "oneOf", "allOf"):
        if key in schema:
            return " or ".join(_type(s) for s in schema[key])
    if "enum" in schema:
        return "one of " + ", ".join(f"`{v}`" for v in schema["enum"])
    kind = schema.get("type", "any")
    if kind == "array":
        return f"array of {_type(schema.get('items', {}))}"
    if kind == "object" and isinstance(schema.get("additionalProperties"), dict):
        return f"object of {_type(schema['additionalProperties'])}"
    return f"{kind} ({schema['format']})" if "format" in schema else str(kind)


def _default(param: dict[str, Any]) -> str:
    schema = param.get("schema", {})
    return f", default `{schema['default']}`" if "default" in schema else ""


def _body(content: dict[str, Any]) -> str:
    parts = (f"`{ctype}`: {_type(c.get('schema', {}))}" for ctype, c in sorted(content.items()))
    return "; ".join(parts)


def _operation(method: str, path: str, op: dict[str, Any]) -> list[str]:
    lines = [f"### {method.upper()} `{path}`", "", op.get("summary", ""), ""]
    if op.get("description"):
        lines += [op["description"].strip(), ""]
    params = op.get("parameters", [])
    if params:
        lines += ["| Parameter | In | Type | Required | Description |", "|---|---|---|---|---|"]
        lines += [
            f"| `{p['name']}` | {p['in']} | {_cell(_type(p.get('schema', {})) + _default(p))} | "
            f"{'yes' if p.get('required') else 'no'} | {_cell(p.get('description', ''))} |"
            for p in params
        ]
        lines.append("")
    body = op.get("requestBody")
    if body:
        required = "required" if body.get("required") else "optional"
        lines += [f"Request body ({required}): {_body(body.get('content', {}))}", ""]
    lines += ["| Status | Description | Body |", "|---|---|---|"]
    lines += [
        f"| {code} | {_cell(r.get('description', ''))} | {_cell(_body(r.get('content', {})))} |"
        for code, r in sorted(op.get("responses", {}).items())
    ]
    return [*lines, ""]


def _component(name: str, schema: dict[str, Any]) -> list[str]:
    lines = [f"### {name}", ""]
    if schema.get("description"):
        lines += [" ".join(schema["description"].split()), ""]
    props = schema.get("properties")
    if not props:
        return [*lines, f"Type: {_type({k: v for k, v in schema.items() if k != 'title'})}", ""]
    required = set(schema.get("required", []))
    lines += ["| Field | Type | Required | Description |", "|---|---|---|---|"]
    lines += [
        f"| `{field}` | {_cell(_type(s))} | {'yes' if field in required else 'no'} | "
        f"{_cell(s.get('description', ''))} |"
        for field, s in props.items()  # declaration order, which is stable
    ]
    return [*lines, ""]


def build() -> str:
    # The schema needs no database: never connect to the one NORM_PG_DSN names.
    saved, normapi.app._DEFAULT_PG_DSN = normapi.app._DEFAULT_PG_DSN, None
    try:
        spec = normapi.app.create_app().openapi()
    finally:
        normapi.app._DEFAULT_PG_DSN = saved
    info = spec["info"]
    lines = [
        "# HTTP API reference",
        "",
        "<!-- Generated by scripts/generate_api_reference.py from the app's OpenAPI schema. "
        "Do not edit by hand; run `uv run python scripts/generate_api_reference.py`. -->",
        "",
        f"{info['title']} {info['version']}, OpenAPI {spec['openapi']}. "
        "The running API serves the same schema as JSON at `/openapi.json`.",
        "",
        "## Operations",
        "",
    ]
    for path in sorted(spec["paths"]):
        item = spec["paths"][path]
        unknown = set(item) - set(_METHODS)
        assert not unknown, f"{path}: add {sorted(unknown)} to _METHODS so it is documented"
        for method in _METHODS:
            if method in item:
                lines += _operation(method, path, item[method])
    lines += ["## Schemas", ""]
    for name, schema in sorted(spec.get("components", {}).get("schemas", {}).items()):
        lines += _component(name, schema)
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(_ROOT)}")
