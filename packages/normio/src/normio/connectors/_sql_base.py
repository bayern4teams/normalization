"""Shared machinery for SQL-backed connectors (Postgres, MySQL).

Two independent layers enforce read-only behavior, per ADR-013:
1. Interface shape — SourceConnector has no write method at all.
2. Actual DB-level permissions — the DSN's user is expected to hold only
   SELECT grants (provisioned via the demo containers' init scripts, see
   tests/integration/fixtures/). This module does not and cannot verify
   the DSN's actual grants; that is the deployment's responsibility, and
   is what tests/integration/test_readonly_connectors.py verifies against
   a real database.

Every query is generated by this module, never by interpolating caller
input into SQL — `table` and `columns` are validated against
`list_tables()`/`information_schema` results and quoted via SQLAlchemy's
identifier quoting, not string-concatenated, to close the SQL-injection
path even though this is an internal, not user-facing, component.
"""

from __future__ import annotations

import json
import os
from typing import TYPE_CHECKING, Any

import pyarrow as pa
import sqlalchemy as sa

if TYPE_CHECKING:
    from collections.abc import Iterator, Sequence

# Bounds peak memory for chunked reads/writes across every SQL-backed
# connector/persistence layer that chunks rows — one shared DEFAULT
# instead of each redefining its own copy of the same number.
ROW_CHUNK_SIZE = 2_000


def _env_rows(name: str, default: int) -> int:
    """A row count from the environment, ignoring anything unusable.

    A malformed or non-positive override must not take the process down
    at import time — falling back to the tested default is strictly
    better than refusing to start because someone typed "2k".
    """
    try:
        value = int(os.environ[name])
    except (KeyError, ValueError):
        return default
    return value if value > 0 else default


# One number used to drive all of the below, which meant tuning any one of
# them silently moved the other three. They have genuinely different
# tradeoffs, so they are now separate knobs that merely happen to share a
# default:
#
# - the source read batch also fixes the resume checkpoint granularity and
#   the window the distinct-value planner dedups over, so raising it buys
#   better dedup at the cost of memory AND coarser resume;
# - the destination insert chunk is the TRANSACTION boundary, so raising
#   it means fewer round trips but more work lost to a mid-chunk crash;
# - the persistence write chunk only bounds memory;
# - the read page size is an API response size.
SOURCE_READ_BATCH_ROWS = _env_rows("NORM_SOURCE_READ_BATCH_ROWS", ROW_CHUNK_SIZE)
DESTINATION_INSERT_CHUNK_ROWS = _env_rows("NORM_DESTINATION_INSERT_CHUNK_ROWS", ROW_CHUNK_SIZE)
PERSISTENCE_WRITE_CHUNK_ROWS = _env_rows("NORM_PERSISTENCE_WRITE_CHUNK_ROWS", ROW_CHUNK_SIZE)
PERSISTENCE_PAGE_ROWS = _env_rows("NORM_PERSISTENCE_PAGE_ROWS", ROW_CHUNK_SIZE)


class SqlConnectorBase:
    source_id: str
    _engine: sa.Engine

    # Which namespace inside the database every table name in this
    # connector is relative to. None means the connection's own default
    # (Postgres: the first entry on `search_path`, normally `public`;
    # MySQL, where a schema IS a database, has nothing else it could be).
    #
    # Everything above this layer keeps passing BARE table names, which is
    # the point: the job's table list, its field_configs, the destination
    # DDL and the clone's own table names all stay unqualified, so a schema
    # costs one argument here and no change anywhere else.
    _schema: str | None = None

    def list_tables(self) -> Sequence[str]:
        inspector = sa.inspect(self._engine)
        return sorted(inspector.get_table_names(schema=self._schema))

    def read_table(
        self,
        table: str,
        *,
        columns: Sequence[str] | None = None,
        batch_size: int = 100_000,
    ) -> Iterator[pa.RecordBatch]:
        metadata = sa.MetaData()
        sql_table = sa.Table(table, metadata, schema=self._schema, autoload_with=self._engine)

        if columns is not None:
            unknown = set(columns) - {c.name for c in sql_table.columns}
            if unknown:
                msg = f"Unknown columns for table {table!r}: {sorted(unknown)}"
                raise ValueError(msg)
            select_columns = [sql_table.c[name] for name in columns]
        else:
            select_columns = list(sql_table.columns)

        column_names = [c.name for c in select_columns]
        # `source_row_key` is the arrival offset, and a resume skips every
        # offset up to its checkpoint, so arrival order must not change
        # between two reads (the ClickHouse connector orders for the same
        # reason). An unordered Postgres scan can join a scan already in
        # flight and start mid-table (synchronize_seqscans): a resumed UK
        # Price Paid clone wrote 406,000 rows twice and 406,000 never.
        query = sa.select(*select_columns).order_by(*self._row_order(sql_table))

        with self._engine.connect() as raw_conn:
            # execution_options(readonly=True) is honored by dialects that
            # support it (e.g. psycopg on Postgres sets the session to a
            # read-only transaction); on dialects without native support
            # this option is a documented, silent no-op — real enforcement
            # still rests on the connection's actual DB-level grants.
            conn = raw_conn.execution_options(stream_results=True, max_row_buffer=batch_size)
            result = conn.execute(query)
            row_offset = 0
            while True:
                rows = result.fetchmany(batch_size)
                if not rows:
                    break
                yield _rows_to_batch(rows, column_names, row_offset, table)
                row_offset += len(rows)

    def _row_order(self, sql_table: sa.Table) -> list[Any]:
        """A total order for `read_table`: the primary key."""
        return list(sql_table.primary_key.columns)

    def close(self) -> None:
        self._engine.dispose()


def _rows_to_batch(
    rows: Sequence[sa.Row[Any]], column_names: list[str], row_offset: int, table_name: str
) -> pa.RecordBatch:
    columns_data: list[list[object]] = [[] for _ in column_names]
    for row in rows:
        for i, value in enumerate(row):
            columns_data[i].append(value)
    arrays = [_to_arrow(col) for col in columns_data]
    keys = pa.array(
        [f"{table_name}:{row_offset + i}" for i in range(len(rows))], type=pa.large_string()
    )
    return pa.RecordBatch.from_arrays([*arrays, keys], names=[*column_names, "source_row_key"])


def _to_arrow(values: list[object]) -> pa.Array:
    """Arrow's own type inference, and for a Python type it has none for
    (`uuid.UUID`: Pagila's PG18 uuidv7 key failed Phase 2 on its first
    batch; also ranges, `inet`) the value's text, which is how the source
    prints it and what Postgres casts back on insert.

    One type family needs more than `str()`: jsonb/json values. psycopg
    hands back parsed `dict`/`list`, and when Arrow cannot unify a column
    of them (mixed shapes — null, array, object) the fallback used to
    `str()` them, which prints PYTHON syntax (`['A', 'B']`, `{'k': True}`)
    — invalid JSON. A `company.aliases` jsonb column hit exactly that on
    a live clone: the destination rejected the chunk with
    `invalid input syntax for type json` (InvalidTextRepresentation),
    which the job cannot report per-value because the insert itself, not
    a normalization, failed. `json.dumps` emits the JSON the column holds;
    every other unmapped type keeps `str()`, which is what its SQL type
    casts back (uuid, inet, ranges)."""
    try:
        return pa.array(values)
    except (pa.ArrowInvalid, pa.ArrowTypeError):
        return pa.array([_fallback_text(v) for v in values], type=pa.string())


def _fallback_text(value: object) -> str | None:
    if value is None:
        return None
    if isinstance(value, (dict, list)):
        return json.dumps(value, ensure_ascii=False)
    return str(value)
