"""LanguageNormalizer — Source.txt Phase 10, §34.

ISO 639 canonicalization via `pycountry.languages.lookup()`:
`English / en / eng` all resolve to the same canonical `en` (alpha_2)
code, falling back to alpha_3 for languages with no two-letter code.
`source_value` is always retained alongside `canonical_code`.

BCP 47 tags (`en-US`, `zh-Hans-CN`, `fr_FR`, `pt-BR`) are parsed before
that lookup. Every one of them used to come back INVALID, because
pycountry only knows bare ISO 639 codes and names — yet a region-tagged
tag is one of the commonest real-world spellings of a language. The
language subtag is what resolves; the script, territory and variant are
NOT discarded but recorded in `structured`, so collapsing `en-US` and
`en-GB` to `en` (which is the point, for matching) stays inspectable.

Babel does the parsing and the deprecated-subtag mapping (`iw` -> `he`,
`in` -> `id`, `mo` -> `ro`; 434 aliases). `langcodes` was evaluated for
this and is not needed — Babel is already a dependency here and covers
both jobs, so adding a second BCP 47 library would buy nothing.

Names come from CLDR too (`_cldr_language_names`, generated by
`scripts/generate_cldr_names.py`), so a language written in its OWN
language resolves: `Deutsch`, `Français`, `español`, `日本語`, `中文`
all used to come back INVALID, because pycountry knows English names
only — and an endonym is the second-commonest real-world spelling of a
language after the bare code.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import TYPE_CHECKING, cast

import babel.core
import blake3
import pyarrow as pa
import pycountry
from normcore.context import NormalizationContext
from normcore.enums import FieldSemanticType, MissingKind, NormalizationStatus, Reversibility
from normcore.models import NormalizedValue
from normcore.pii import character_class_mask, content_hash
from normcore.rules import ComponentVersionInfo, ExplanationText, ValidationOutcome
from normcore.trace import TraceStep

from normalizers import text_ops
from normalizers._cldr_language_names import CLDR_LANGUAGE_NAMES

if TYPE_CHECKING:
    from collections.abc import Sequence

    from normcore.interfaces import ComponentVersion, Explanation, StepSpec, ValidationResult

_VERSION = "0.1.0"
_PARSE_PARAMS_HASH = blake3.blake3(b"{}").hexdigest()

# BCP 47 allows "-"; real data (and POSIX locale strings) also use "_".
_TAG_SEPARATORS = ("-", "_")

# Deprecated ISO 639 subtags CLDR maps to their modern equivalent.
_LANGUAGE_ALIASES: Mapping[str, str] = babel.core.get_global("language_aliases")


class _StaticStepSpec:
    def __init__(self, step_id: str, operation: str, reversibility: Reversibility, lossy: bool):
        self.step_id = step_id
        self.operation = operation
        self.claimed_reversibility = reversibility
        self.lossy = lossy


_RESOLVE_STEP = _StaticStepSpec(
    "language.resolve", "language.resolve", Reversibility.PARTIALLY_REVERSIBLE, True
)
_STATIC_STEPS: tuple[_StaticStepSpec, ...] = (_RESOLVE_STEP,)


class LanguageNormalizer:
    name = "LanguageNormalizer"
    supported_types = frozenset({FieldSemanticType.LANGUAGE})

    def can_handle(self, field_type: FieldSemanticType, ctx: NormalizationContext) -> bool:
        return field_type in self.supported_types

    def normalize(self, value: str | None, ctx: NormalizationContext) -> NormalizedValue:
        if value is None:
            return _missing(None, MissingKind.NULL, ctx)
        if value.strip() == "":
            return _missing(value, MissingKind.EMPTY_STRING, ctx)

        # Same edge set COUNTRY resolves by: a lookup value wrapped in
        # list or path separators (`/en`, `, , , , USD`) is the value.
        cleaned, _ = text_ops.strip_enclosing_separators(value)
        subtag, tag_parts = _split_language_tag(cleaned)
        language = _resolve_language(subtag)
        if language is None:
            return _unresolved(value, ctx)

        canonical_code = getattr(language, "alpha_2", None) or language.alpha_3

        structured = {
            "source_value": cleaned,
            "canonical_code": canonical_code,
            "language_name": language.name,
            # Present (and non-null) only for a tag that actually carried
            # them — what "en-US" means beyond "en" is not thrown away.
            **tag_parts,
        }

        return NormalizedValue(
            original=value,
            display=language.name,
            comparison=canonical_code,
            search=canonical_code,
            structured=structured,
            validation_status="VALID",
            normalization_status=NormalizationStatus.NORMALIZED,
            confidence=1.0,
            trace=[_resolve_trace_step(value, changed=True)],
            lossiness=Reversibility.PARTIALLY_REVERSIBLE,
            profile_version="",
            env_id="",
            semantic_type=ctx.semantic_type,
            context_hash=ctx.context_hash,
        )

    def normalize_batch(self, values: pa.Array, ctx: NormalizationContext) -> pa.StructArray:
        results = [self.normalize(v, ctx) for v in values.to_pylist()]
        return pa.StructArray.from_arrays(
            [
                pa.array([r.original for r in results], type=pa.large_string()),
                pa.array([r.display for r in results], type=pa.large_string()),
                pa.array([r.comparison for r in results], type=pa.large_string()),
                pa.array([r.normalization_status.value for r in results], type=pa.large_string()),
            ],
            names=["original", "display", "comparison", "status"],
        )

    def validate(self, value: str | None, ctx: NormalizationContext) -> ValidationResult:
        result = self.normalize(value, ctx)
        if result.original_kind is not None:
            return ValidationOutcome(
                is_valid=False, status="MISSING", reason=result.original_kind.value
            )
        is_valid = result.normalization_status is not NormalizationStatus.INVALID
        return ValidationOutcome(
            is_valid=is_valid,
            status=result.validation_status or "UNKNOWN",
            reason=None if is_valid else "unrecognized language",
        )

    def explain(self, result: NormalizedValue) -> Explanation:
        if result.normalization_status is NormalizationStatus.INVALID:
            return ExplanationText(
                plain_language="Not a recognized language name or code.",
                technical=f"errors={result.errors}",
            )
        code = result.structured.get("canonical_code")
        return ExplanationText(
            plain_language=f"Resolved to {result.display} ({code}).",
            technical=f"structured={result.structured}",
        )

    def version(self) -> ComponentVersion:
        return ComponentVersionInfo(name=self.name, version=_VERSION)

    def steps(self) -> Sequence[StepSpec]:
        return _STATIC_STEPS

    def inverse(self, step_id: str, value: str) -> str | None:
        return None


def _split_language_tag(cleaned: str) -> tuple[str, dict[str, str]]:
    """Split a BCP 47 tag into its language subtag and the rest.

    Returns the value unchanged when it is not tag-shaped, so plain codes
    and names ("en", "English") take exactly the path they always did.
    Parsing is syntactic only — Babel happily parses "xx-YY" — so the
    subtag is still validated against ISO 639 by `_resolve_language`.
    """
    if not any(sep in cleaned for sep in _TAG_SEPARATORS):
        return cleaned, {}

    for separator in _TAG_SEPARATORS:
        if separator not in cleaned:
            continue
        try:
            parsed = babel.core.parse_locale(cleaned, sep=separator)
        except (ValueError, TypeError):
            continue
        # Babel returns a 4-tuple, or a 5-tuple when the tag carries a
        # modifier ("ca_ES@valencia"). Indexing rather than unpacking
        # keeps both shapes working.
        language, territory, script, variant = parsed[0], parsed[1], parsed[2], parsed[3]
        if not language:
            continue
        # An alias may itself carry a script ("sh" -> "sr_Latn").
        alias = _LANGUAGE_ALIASES.get(language, language)
        alias_language, _, alias_script = alias.partition("_")
        parts = {
            "tag_script": script or alias_script or None,
            "tag_territory": territory,
            "tag_variant": variant,
        }
        return alias_language, {k: v for k, v in parts.items() if v}

    return cleaned, {}


def _resolve_language(cleaned: str) -> pycountry.db.Data | None:
    """Tries exact ISO 639 code fields FIRST, before falling back to
    `pycountry.languages.lookup()`'s generic (code-or-name) search.

    Found empirically in M4: `pycountry.languages.lookup("en")` does NOT
    return English — it returns a different, obscure language whose
    `name` field happens to be the two-letter string "En" (alpha_3
    "enc"), because `lookup()` apparently checks name equality before —
    or instead of — an exact alpha_2 code match for short inputs. Trying
    `get(alpha_2=...)` / `get(alpha_3=...)` explicitly first sidesteps
    this entirely for the common case of a real ISO code being passed
    in, and `lookup()` remains the fallback for full names ("English")
    where this bug does not manifest.
    """
    lowered = cleaned.lower()
    if len(lowered) == 2:
        exact = pycountry.languages.get(alpha_2=lowered)
        if exact is not None:
            return cast("pycountry.db.Data", exact)
    if len(lowered) == 3:
        exact = pycountry.languages.get(alpha_3=lowered)
        if exact is not None:
            return cast("pycountry.db.Data", exact)
    try:
        return cast("pycountry.db.Data", pycountry.languages.lookup(cleaned))
    except LookupError:
        pass

    # Deprecated subtag, last. pycountry stays the authority, so a code it
    # still recognizes keeps its own answer ("sh" is a live pycountry
    # entry and is NOT rewritten to CLDR's "sr_Latn"). Without this a
    # bare "iw" was INVALID while "iw-IL" resolved, purely because only
    # the tagged form went through the alias map.
    alias = _LANGUAGE_ALIASES.get(lowered)
    if alias is not None:
        alias_language, _, _ = alias.partition("_")
        resolved = pycountry.languages.get(alpha_2=alias_language) or pycountry.languages.get(
            alpha_3=alias_language
        )
        if resolved is not None:
            return cast("pycountry.db.Data", resolved)

    # CLDR endonyms and translated names, last: pycountry stays the
    # authority, and a two-letter Latin name is excluded at generation
    # time so this can never shadow an ISO 639-1 code.
    subtag = CLDR_LANGUAGE_NAMES.get(cleaned.casefold())
    if subtag is not None:
        by_name = pycountry.languages.get(alpha_2=subtag) or pycountry.languages.get(alpha_3=subtag)
        if by_name is not None:
            return cast("pycountry.db.Data", by_name)
    return None


def _unresolved(value: str, ctx: NormalizationContext) -> NormalizedValue:
    return NormalizedValue(
        original=value,
        display=value,
        normalization_status=NormalizationStatus.INVALID,
        validation_status="INVALID",
        confidence=0.0,
        errors=["not a recognized language name or code"],
        structured={},
        trace=[_resolve_trace_step(value, changed=False)],
        lossiness=Reversibility.LOSSLESS,
        profile_version="",
        env_id="",
        semantic_type=ctx.semantic_type,
        context_hash=ctx.context_hash,
    )


def _missing(value: str | None, kind: MissingKind, ctx: NormalizationContext) -> NormalizedValue:
    return NormalizedValue(
        original=value,
        original_kind=kind,
        normalization_status=NormalizationStatus.NORMALIZED,
        validation_status="MISSING",
        confidence=1.0,
        profile_version="",
        env_id="",
        semantic_type=ctx.semantic_type,
        context_hash=ctx.context_hash,
    )


def _resolve_trace_step(value: str, *, changed: bool) -> TraceStep:
    return TraceStep(
        step_order=1,
        rule_id="language.resolve",
        operation="language.resolve",
        params_hash=_PARSE_PARAMS_HASH,
        input_hash=content_hash(value),
        output_hash=content_hash(value),
        input_mask=character_class_mask(value),
        output_mask=character_class_mask(value),
        changed=changed,
        lossy=True,
        reversibility=Reversibility.PARTIALLY_REVERSIBLE,
        library="pycountry",
        library_version="24.x",
    )
