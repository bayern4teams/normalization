"""CurrencyNormalizer — Source.txt Phase 12, §47.

`$ / USD / US$ / US Dollars` resolve to `USD` only WITH context — a bare
`$` alone stays ambiguous (it is legal tender symbol for over 20
currencies). Inference draws on the value's own currency CODE (ISO 4217,
unambiguous by construction) or symbol PLUS `ctx.country`/`ctx.locale` —
never the symbol alone.

Names and symbols come from CLDR (`_cldr_currency_names`, generated by
`scripts/generate_cldr_names.py`), so `US-Dollar`, `Yen japonais`,
`₹`, `₽` and `A$` resolve without anyone listing them — 22.8k names and
197 symbols, against the 8 names and 3 symbols this module used to carry
by hand. §47's rule survives that unchanged, and for free: a name or
symbol that means DIFFERENT currencies in different locales is dropped at
generation time, which is exactly what removes `$` (USD in en_US, CAD in
en_CA), `¥` (JPY in ja, CNY in zh) and `kr` (four Nordic currencies).
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING

import blake3
import pyarrow as pa
import pycountry
from normcore.context import NormalizationContext
from normcore.enums import FieldSemanticType, MissingKind, NormalizationStatus, Reversibility
from normcore.models import NormalizedValue
from normcore.pii import character_class_mask, content_hash
from normcore.rules import ComponentVersionInfo, ExplanationText, ValidationOutcome
from normcore.trace import TraceStep

from normalizers import text_ops
from normalizers._cldr_currency_names import CLDR_CURRENCY_NAMES, CLDR_CURRENCY_SYMBOLS

if TYPE_CHECKING:
    from collections.abc import Sequence

    from normcore.interfaces import ComponentVersion, Explanation, StepSpec, ValidationResult

_VERSION = "0.1.0"
_PARSE_PARAMS_HASH = blake3.blake3(b"{}").hexdigest()
_ISO_CODE_LENGTH = 3

# ISO 4217 codes are unambiguous by construction — recognizing one in the
# text always resolves confidently, no context required. The regex alone
# only finds candidate 3-uppercase-letter tokens ("ABC", "SKU", "TBD" all
# match) — pycountry.currencies (already a dependency) is what actually
# confirms one is a real ISO 4217 code before it's accepted at confidence
# 1.0; a candidate that isn't real falls through to the other resolution
# strategies below instead of being accepted blind.
_ISO_CODE_RE = re.compile(r"\b([A-Z]{3})\b")

# Lowercase codes ("usd") are just as unambiguous as uppercase ones, but
# case-insensitive matching anywhere in the text would resolve ordinary
# prose — "cup of tea" contains CUP, a real ISO 4217 code. Accepting a
# case-insensitive code only when it is the value's ONLY alphabetic token
# keeps "usd" and "1234.56 usd" working while leaving prose alone.
_ALPHA_TOKEN_RE = re.compile(r"[^\W\d_]+")

# ISO 4217 numeric codes ("840") are exactly 3 digits. Only matched when
# they are the whole value, so a bare amount in a CURRENCY column is not
# mistaken for a code.
_NUMERIC_CODE_RE = re.compile(r"^\d{3}$")


def _is_real_iso_code(code: str) -> bool:
    return pycountry.currencies.get(alpha_3=code) is not None


# Symbols are inherently ambiguous (§47) EXCEPT where a symbol is only
# used by one currency IN PRACTICE — which is a judgement CLDR does not
# make, so these three stay hand-curated and are consulted BEFORE the
# generated table. CLDR drops "¥" (ja uses it for JPY, zh for CNY) and
# has no unambiguous entry for "£" (several locales use it for their own
# pound), yet in real-world data both overwhelmingly mean JPY and GBP.
_UNAMBIGUOUS_SYMBOLS: dict[str, str] = {
    "€": "EUR",
    "£": "GBP",
    "¥": "JPY",
}

# Symbols safe to look for ANYWHERE in the value ("₹1,234"). A symbol
# containing letters is only ever matched against the whole value: "Ar",
# "Br", "Ft" and "kr" are ordinary words in some language, and scanning
# for them inside free text is the same mistake as matching the ISO code
# "CUP" inside "cup of tea".
_SUBSTRING_SYMBOLS: dict[str, str] = {
    symbol: code
    for symbol, code in CLDR_CURRENCY_SYMBOLS.items()
    if not any(ch.isalpha() for ch in symbol)
}

# "$" specifically requires country/locale context — curated from
# common real-world data, not exhaustive.
_DOLLAR_COUNTRY_MAP: dict[str, str] = {
    "US": "USD",
    "CA": "CAD",
    "AU": "AUD",
    "NZ": "NZD",
    "SG": "SGD",
    "HK": "HKD",
}

# CLDR ships singular display names only ("US Dollar"), so the plural and
# colloquial spellings real data actually contains stay hand-listed.
_NAME_MAP: dict[str, str] = {
    "us dollars": "USD",
    "united states dollar": "USD",  # CLDR's own en name is "US Dollar"
    "euros": "EUR",
    "british pound": "GBP",
    "pound sterling": "GBP",
}


class _StaticStepSpec:
    def __init__(self, step_id: str, operation: str, reversibility: Reversibility, lossy: bool):
        self.step_id = step_id
        self.operation = operation
        self.claimed_reversibility = reversibility
        self.lossy = lossy


_RESOLVE_STEP = _StaticStepSpec(
    "currency.resolve", "currency.resolve", Reversibility.PARTIALLY_REVERSIBLE, True
)
_STATIC_STEPS: tuple[_StaticStepSpec, ...] = (_RESOLVE_STEP,)


class CurrencyNormalizer:
    name = "CurrencyNormalizer"
    supported_types = frozenset({FieldSemanticType.CURRENCY})

    def can_handle(self, field_type: FieldSemanticType, ctx: NormalizationContext) -> bool:
        return field_type in self.supported_types

    def normalize(self, value: str | None, ctx: NormalizationContext) -> NormalizedValue:
        if value is None:
            return _missing(None, MissingKind.NULL, ctx)
        if value.strip() == "":
            return _missing(value, MissingKind.EMPTY_STRING, ctx)

        # Same edge set COUNTRY resolves by: a lookup value wrapped in
        # list or path separators (`/en`, `, , , , USD`) is the value.
        cleaned, _ = text_ops.strip_enclosing_separators(value)
        canonical, confidence = _resolve_currency(cleaned, ctx)

        if canonical is None:
            return _ambiguous(value, ctx)

        structured = {
            "original_currency": cleaned,
            "canonical_currency": canonical,
            "currency_confidence": confidence,
        }
        return NormalizedValue(
            original=value,
            display=canonical,
            comparison=canonical,
            search=canonical,
            structured=structured,
            validation_status="VALID",
            normalization_status=NormalizationStatus.NORMALIZED,
            confidence=confidence,
            trace=[_resolve_trace_step(value, changed=True)],
            lossiness=Reversibility.PARTIALLY_REVERSIBLE,
            profile_version="",
            env_id="",
            semantic_type=ctx.semantic_type,
            context_hash=ctx.context_hash,
        )

    def normalize_batch(self, values: pa.Array, ctx: NormalizationContext) -> pa.StructArray:
        results = [self.normalize(v, ctx) for v in values.to_pylist()]
        return pa.StructArray.from_arrays(
            [
                pa.array([r.original for r in results], type=pa.large_string()),
                pa.array([r.display for r in results], type=pa.large_string()),
                pa.array([r.comparison for r in results], type=pa.large_string()),
                pa.array([r.normalization_status.value for r in results], type=pa.large_string()),
            ],
            names=["original", "display", "comparison", "status"],
        )

    def validate(self, value: str | None, ctx: NormalizationContext) -> ValidationResult:
        result = self.normalize(value, ctx)
        if result.original_kind is not None:
            return ValidationOutcome(
                is_valid=False, status="MISSING", reason=result.original_kind.value
            )
        is_valid = result.normalization_status is not NormalizationStatus.AMBIGUOUS
        return ValidationOutcome(
            is_valid=is_valid,
            status=result.validation_status or "UNKNOWN",
            reason=None if is_valid else "ambiguous currency symbol without context",
        )

    def explain(self, result: NormalizedValue) -> Explanation:
        if result.normalization_status is NormalizationStatus.AMBIGUOUS:
            return ExplanationText(
                plain_language="Currency symbol is ambiguous without country/locale context.",
                technical="AMBIGUOUS: bare symbol, no disambiguating context",
            )
        return ExplanationText(
            plain_language=f"Resolved to {result.display}.",
            technical=f"structured={result.structured}",
        )

    def version(self) -> ComponentVersion:
        return ComponentVersionInfo(name=self.name, version=_VERSION)

    def steps(self) -> Sequence[StepSpec]:
        return _STATIC_STEPS

    def inverse(self, step_id: str, value: str) -> str | None:
        return None


def _resolve_iso_code(cleaned: str) -> str | None:
    """ISO 4217 codes, alphabetic or numeric — all unambiguous by
    construction, so any hit here resolves at confidence 1.0."""
    # .finditer(), not .search(): a value can contain more than one
    # candidate 3-letter token ("SKU USD" has two) — check each for a real
    # ISO 4217 code rather than accepting or rejecting based on whichever
    # comes first.
    for iso_match in _ISO_CODE_RE.finditer(cleaned):
        candidate = iso_match.group(1)
        if _is_real_iso_code(candidate):
            return candidate

    alpha_tokens = _ALPHA_TOKEN_RE.findall(cleaned)
    if len(alpha_tokens) == 1:
        candidate = str(alpha_tokens[0]).upper()
        if len(candidate) == _ISO_CODE_LENGTH and _is_real_iso_code(candidate):
            return candidate

    if _NUMERIC_CODE_RE.match(cleaned):
        by_numeric = pycountry.currencies.get(numeric=cleaned)
        if by_numeric is not None:
            return str(by_numeric.alpha_3)

    return None


def _resolve_name(lowered: str) -> str | None:
    """A currency NAME is only ever matched against the WHOLE value.

    CLDR names include short real words ("yen", "kip", "lek", "sol",
    "gold"), so finding one inside a sentence would resolve prose — the
    same mistake as matching the ISO code "CUP" inside "cup of tea".
    """
    return _NAME_MAP.get(lowered) or CLDR_CURRENCY_NAMES.get(lowered)


def _resolve_symbol(cleaned: str) -> str | None:
    """Hand-curated symbols, then CLDR's whole-value, then CLDR's scannable."""
    for symbol, code in _UNAMBIGUOUS_SYMBOLS.items():
        if symbol in cleaned:
            return code

    # Whole-value before substring, so the letter-bearing symbols ("A$",
    # "R$", "$US", "Afl.", "zł") resolve without ever being scanned for
    # inside free text.
    exact = CLDR_CURRENCY_SYMBOLS.get(cleaned)
    if exact is not None:
        return exact

    for symbol, code in _SUBSTRING_SYMBOLS.items():
        if symbol in cleaned:
            return code
    return None


def _resolve_currency(cleaned: str, ctx: NormalizationContext) -> tuple[str | None, float]:
    iso_code = _resolve_iso_code(cleaned)
    if iso_code is not None:
        return iso_code, 1.0

    name = _resolve_name(cleaned.casefold())
    if name is not None:
        return name, 1.0

    symbol = _resolve_symbol(cleaned)
    if symbol is not None:
        return symbol, 0.95

    # "$" reaches here only when it is NOT one of the disambiguated forms
    # above ("A$", "CA$", "$US"), so a bare "$" needs context or stays
    # ambiguous — never guessed (§47).
    #
    # The value must BE the sign, not merely contain it. `"$" in cleaned`
    # made any string with a dollar sign anywhere in it resolve to the
    # context country's dollar: measured on a real source, the range
    # strings `$5 mil. - $10 mil.` and `Under $500,000` all came back VALID
    # USD at 0.8 confidence under `country=US`. That is a guess about
    # arbitrary prose, which §47 and this project's "never guess on
    # ambiguous data" rule both forbid — and it is the same class of bug
    # the disambiguated forms above exist to avoid.
    if cleaned.strip() == "$":
        country = (ctx.country or "").upper()
        if country in _DOLLAR_COUNTRY_MAP:
            return _DOLLAR_COUNTRY_MAP[country], 0.8

    return None, 0.0


def _ambiguous(value: str, ctx: NormalizationContext) -> NormalizedValue:
    return NormalizedValue(
        original=value,
        display=value,
        structured={"original_currency": value, "canonical_currency": None},
        validation_status="AMBIGUOUS",
        normalization_status=NormalizationStatus.AMBIGUOUS,
        confidence=0.0,
        trace=[_resolve_trace_step(value, changed=False)],
        lossiness=Reversibility.LOSSLESS,
        profile_version="",
        env_id="",
        semantic_type=ctx.semantic_type,
        context_hash=ctx.context_hash,
    )


def _missing(value: str | None, kind: MissingKind, ctx: NormalizationContext) -> NormalizedValue:
    return NormalizedValue(
        original=value,
        original_kind=kind,
        normalization_status=NormalizationStatus.NORMALIZED,
        validation_status="MISSING",
        confidence=1.0,
        profile_version="",
        env_id="",
        semantic_type=ctx.semantic_type,
        context_hash=ctx.context_hash,
    )


def _resolve_trace_step(value: str, *, changed: bool) -> TraceStep:
    return TraceStep(
        step_order=1,
        rule_id="currency.resolve",
        operation="currency.resolve",
        params_hash=_PARSE_PARAMS_HASH,
        input_hash=content_hash(value),
        output_hash=content_hash(value),
        input_mask=character_class_mask(value),
        output_mask=character_class_mask(value),
        changed=changed,
        lossy=True,
        reversibility=Reversibility.PARTIALLY_REVERSIBLE,
        library="normalizers",
        library_version=_VERSION,
    )
